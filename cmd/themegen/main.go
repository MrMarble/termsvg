// Theme generator tool for termsvg.
// Reads JSON theme files from themes/ directory and generates Go code.
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"image/color"
	"io"
	"os"
	"path/filepath"
	"strings"
	"text/template"
	"time"

	termcolor "github.com/mrmarble/termsvg/internal/color"
	"golang.org/x/text/cases"
	"golang.org/x/text/language"
)

// ThemeData represents the JSON structure of a theme file.
type ThemeData struct {
	Fg      string `json:"fg"`
	Bg      string `json:"bg"`
	Palette string `json:"palette"`
}

// ThemeInfo holds parsed theme data for code generation.
type ThemeInfo struct {
	Name             string
	VarName          string
	Fg               string
	Bg               string
	PaletteOverrides string
	WindowBg         string
}

// TemplateData holds data for the builtin theme template.
type TemplateData struct {
	GeneratedAt string
	Themes      []ThemeInfo
}

const builtinTemplate = `// Code generated by themegen. DO NOT EDIT.
// Generated at: {{ .GeneratedAt }}

package theme

import (
	"image/color"

	termcolor "github.com/mrmarble/termsvg/internal/color"
)

// builtinThemes is a registry of all built-in themes.
var builtinThemes = map[string]Theme{
{{- range .Themes }}
	"{{ .Name }}": {{ .VarName }},
{{- end }}
}

{{ range .Themes }}
// {{ .VarName }} is the "{{ .Name }}" theme.
var {{ .VarName }} = Theme{
	Name:       "{{ .Name }}",
	Foreground: color.RGBA{ {{ .Fg }} },
	Background: color.RGBA{ {{ .Bg }} },
	Palette:    {{ .VarName }}Palette,
	WindowBackground: color.RGBA{ {{ .WindowBg }} },
	WindowButtons: [3]color.RGBA{
		{R: 255, G: 95, B: 86, A: 255},  // Close
		{R: 255, G: 189, B: 46, A: 255}, // Minimize
		{R: 24, G: 193, B: 50, A: 255},  // Maximize
	},
}

// {{ .VarName }}Palette is the color palette for the "{{ .Name }}" theme.
// It extends the standard xterm palette with custom colors for the first 16 ANSI colors.
var {{ .VarName }}Palette = func() termcolor.Palette {
	p := termcolor.Standard()
	{{ .PaletteOverrides }}
	return p
}()
{{ end }}
`

func main() {
	count, outputFile, err := run()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %d themes in %s\n", count, outputFile)
}

// run locates the themes directory and output file relative to the working
// directory, then generates the built-in theme source.
func run() (count int, outputFile string, err error) {
	themesDir := "themes"
	if _, err := os.Stat(themesDir); os.IsNotExist(err) {
		// Try from internal/theme directory
		themesDir = "../../themes"
		if _, err := os.Stat(themesDir); os.IsNotExist(err) {
			return 0, "", errors.New("themes directory not found")
		}
	}

	outputFile = "internal/theme/builtin.go"
	if _, err := os.Stat("internal/theme"); os.IsNotExist(err) {
		outputFile = "builtin.go"
	}

	count, err = generate(themesDir, outputFile, os.Stderr)
	return count, outputFile, err
}

// generate reads every theme JSON file in themesDir and writes the Go source
// registering them to outputFile. Unparsable files are reported on warn and skipped.
func generate(themesDir, outputFile string, warn io.Writer) (count int, err error) {
	entries, err := os.ReadDir(themesDir)
	if err != nil {
		return 0, fmt.Errorf("reading themes directory: %w", err)
	}

	themes := make([]ThemeInfo, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}

		theme, err := parseThemeFile(filepath.Join(themesDir, entry.Name()))
		if err != nil {
			fmt.Fprintf(warn, "Warning: failed to parse %s: %v\n", entry.Name(), err)
			continue
		}

		themes = append(themes, theme)
	}

	if len(themes) == 0 {
		return 0, errors.New("no valid theme files found")
	}

	tmpl, err := template.New("builtin").Parse(builtinTemplate)
	if err != nil {
		return 0, fmt.Errorf("parsing template: %w", err)
	}

	file, err := os.Create(outputFile) //nolint:gosec // output path is chosen by the tool
	if err != nil {
		return 0, fmt.Errorf("creating output file: %w", err)
	}

	data := TemplateData{GeneratedAt: time.Now().Format(time.RFC3339), Themes: themes}
	execErr := tmpl.Execute(file, data)
	if err := errors.Join(execErr, file.Close()); err != nil {
		return 0, fmt.Errorf("writing %s: %w", outputFile, err)
	}

	return len(themes), nil
}

func parseThemeFile(path string) (ThemeInfo, error) {
	data, err := os.ReadFile(path) //nolint:gosec // path is validated theme file
	if err != nil {
		return ThemeInfo{}, err
	}

	var themeData ThemeData
	if err := json.Unmarshal(data, &themeData); err != nil {
		return ThemeInfo{}, err
	}

	// Validate palette has 16 colors
	colors := strings.Split(themeData.Palette, ":")
	if len(colors) != 16 {
		return ThemeInfo{}, fmt.Errorf("palette must have 16 colors, got %d", len(colors))
	}

	// Get theme name from filename
	name := strings.TrimSuffix(filepath.Base(path), ".json")

	// Create variable name (camelCase)
	varName := toVarName(name)

	// Parse colors (foreground/background use field format)
	fgRGBA, err := termcolor.ParseHex(themeData.Fg)
	if err != nil {
		return ThemeInfo{}, fmt.Errorf("invalid fg %q: %w", themeData.Fg, err)
	}
	bgRGBA, err := termcolor.ParseHex(themeData.Bg)
	if err != nil {
		return ThemeInfo{}, fmt.Errorf("invalid bg %q: %w", themeData.Bg, err)
	}
	fg, bg := rgbaFields(fgRGBA), rgbaFields(bgRGBA)

	// Build palette overrides (only first 16 colors)
	paletteOverrides := make([]string, 0, len(colors))
	for i, c := range colors {
		rgba, err := termcolor.ParseHex(c)
		if err != nil {
			return ThemeInfo{}, fmt.Errorf("invalid palette color %d %q: %w", i, c, err)
		}
		paletteOverrides = append(paletteOverrides, fmt.Sprintf("p[%d] = color.RGBA{%s}", i, rgbaFields(rgba)))
	}

	// Window background uses the theme's bg property (terminal background)
	windowBg := bg

	return ThemeInfo{
		Name:             name,
		VarName:          varName,
		Fg:               fg,
		Bg:               bg,
		PaletteOverrides: strings.Join(paletteOverrides, "\n\t"),
		WindowBg:         windowBg,
	}, nil
}

func toVarName(name string) string {
	// Convert kebab-case to CamelCase
	parts := strings.Split(name, "-")
	caser := cases.Title(language.English)
	for i, part := range parts {
		parts[i] = caser.String(part)
	}
	return strings.Join(parts, "")
}

// rgbaFields renders a color as the field list of a color.RGBA literal.
func rgbaFields(c color.RGBA) string {
	return fmt.Sprintf("R: %d, G: %d, B: %d, A: %d", c.R, c.G, c.B, c.A)
}

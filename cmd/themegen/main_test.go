const validPalette = "#000000:#111111:#222222:#333333:#444444:#555555:#666666:#777777:" +
	"#888888:#999999:#aaaaaa:#bbbbbb:#cccccc:#dddddd:#eeeeee:#ffffff"

func TestRGBAFields(t *testing.T) {
	got := rgbaFields(color.RGBA{R: 255, G: 87, B: 51, A: 255})
	if want := "R: 255, G: 87, B: 51, A: 255"; got != want {
		t.Errorf("rgbaFields() = %q, want %q", got, want)
	}
}

func TestToVarName(t *testing.T) {
	tests := map[string]string{
		"dracula":        "Dracula",
		"gruvbox-dark":   "GruvboxDark",
		"solarized-dark": "SolarizedDark",
		"a-b-c":          "ABC",
	}
	for in, want := range tests {
		t.Run(in, func(t *testing.T) {
			if got := toVarName(in); got != want {
				t.Errorf("toVarName(%q) = %q, want %q", in, got, want)
			}
		})
	}
}

func TestParseThemeFile(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) string {
		t.Helper()
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
		return p
	}

	t.Run("valid", func(t *testing.T) {
		p := write("my-theme.json", `{"fg":"#ffffff","bg":"#000000","palette":"`+validPalette+`"}`)
		info, err := parseThemeFile(p)
		if err != nil {
			t.Fatal(err)
		}
		if info.Name != "my-theme" || info.VarName != "MyTheme" {
			t.Errorf("name/var = %q/%q", info.Name, info.VarName)
		}
		if info.Fg != "R: 255, G: 255, B: 255, A: 255" || info.WindowBg != info.Bg {
			t.Errorf("colors = %+v", info)
		}
		if n := strings.Count(info.PaletteOverrides, "p["); n != 16 {
			t.Errorf("palette overrides = %d, want 16", n)
		}
	})
	t.Run("wrong palette size", func(t *testing.T) {
		p := write("short.json", `{"fg":"#fff","bg":"#000","palette":"#000:#fff"}`)
		if _, err := parseThemeFile(p); err == nil || !strings.Contains(err.Error(), "16 colors") {
			t.Errorf("error = %v", err)
		}
	})
	for name, theme := range map[string]string{
		"invalid fg":      `{"fg":"zz","bg":"#000","palette":"` + validPalette + `"}`,
		"invalid bg":      `{"fg":"#fff","bg":"12","palette":"` + validPalette + `"}`,
		"invalid palette": `{"fg":"#fff","bg":"#000","palette":"` + strings.Replace(validPalette, "#111111", "#11111g", 1) + `"}`,
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := parseThemeFile(write(strings.ReplaceAll(name, " ", "-")+".json", theme)); err == nil {
				t.Error("expected error")
			}
		})
	}
	t.Run("invalid json", func(t *testing.T) {
		if _, err := parseThemeFile(write("bad.json", "{")); err == nil {
			t.Error("expected error")
		}
	})
	t.Run("missing file", func(t *testing.T) {
		if _, err := parseThemeFile(filepath.Join(dir, "absent.json")); err == nil {
			t.Error("expected error")
		}
	})
}

func TestGenerate(t *testing.T) {
	themes := t.TempDir()
	good := `{"fg":"#ffffff","bg":"#000000","palette":"` + validPalette + `"}`
	for name, content := range map[string]string{
		"alpha-theme.json": good,
		"beta.json":        good,
		"broken.json":      "{",
		"notes.txt":        "ignored",
	} {
		if err := os.WriteFile(filepath.Join(themes, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Mkdir(filepath.Join(themes, "sub.json"), 0o750); err != nil {
		t.Fatal(err)
	}

	out := filepath.Join(t.TempDir(), "builtin.go")
	var warn bytes.Buffer
	count, err := generate(themes, out, &warn)
	if err != nil {
		t.Fatal(err)
	}
	if count != 2 {
		t.Errorf("count = %d, want 2", count)
	}
	if !strings.Contains(warn.String(), "broken.json") {
		t.Errorf("warning missing for broken.json: %q", warn.String())
	}
	src, err := os.ReadFile(out) //nolint:gosec // test temp file
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"Code generated by themegen", `"alpha-theme": AlphaTheme`, "var BetaPalette"} {
		if !strings.Contains(string(src), want) {
			t.Errorf("generated source missing %q", want)
		}
	}
	if _, err := format.Source(src); err != nil {
		t.Errorf("generated source is not valid Go: %v", err)
	}
}

func TestGenerate_Errors(t *testing.T) {
	out := filepath.Join(t.TempDir(), "builtin.go")
	if _, err := generate(filepath.Join(t.TempDir(), "missing"), out, io.Discard); err == nil {
		t.Error("expected error for missing themes directory")
	}
	if _, err := generate(t.TempDir(), out, io.Discard); err == nil {
		t.Error("expected error when no valid themes exist")
	}

	themes := t.TempDir()
	good := `{"fg":"#fff","bg":"#000","palette":"` + validPalette + `"}`
	if err := os.WriteFile(filepath.Join(themes, "a.json"), []byte(good), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := generate(themes, filepath.Join(themes, "no-dir", "builtin.go"), io.Discard); err == nil {
		t.Error("expected error for unwritable output")
	}
}

func TestGenerate_MatchesCheckedInThemes(t *testing.T) {
	out := filepath.Join(t.TempDir(), "builtin.go")
	count, err := generate(filepath.Join("..", "..", "themes"), out, io.Discard)
	if err != nil || count == 0 {
		t.Fatalf("generate() = %d, %v", count, err)
	}
	got, _ := os.ReadFile(out) //nolint:gosec // test temp file
	want, err := os.ReadFile(filepath.Join("..", "..", "internal", "theme", "builtin.go"))
	if err != nil {
		t.Fatal(err)
	}
	strip := func(b []byte) string {
		formatted, ferr := format.Source(b)
		if ferr != nil {
			t.Fatal(ferr)
		}
		lines := strings.Split(string(formatted), "\n")
		kept := lines[:0]
		for _, l := range lines {
			if !strings.HasPrefix(l, "// Generated at:") {
				kept = append(kept, l)
			}
		}
		return strings.Join(kept, "\n")
	}
	if strip(got) != strip(want) {
		t.Error("internal/theme/builtin.go is stale; run `go generate ./internal/theme/`")
	}
}
